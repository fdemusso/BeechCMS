import { join } from 'node:path'
import { beforeEach, describe, expect, it, vi } from 'vitest'

vi.mock('node:child_process', () => ({ spawnSync: vi.fn() }))
vi.mock('node:fs', () => ({
  writeFileSync: vi.fn(), rmSync: vi.fn(), existsSync: vi.fn(() => false),
  readFileSync: vi.fn(), readdirSync: vi.fn(),
}))
vi.mock('node:os', () => ({ tmpdir: () => '/tmp/Mario Rossi' }))

import { spawnSync } from 'node:child_process'
import { readFileSync, rmSync, writeFileSync } from 'node:fs'
import { executeD1File, findTopLevelObjectSpan, queryD1, resolveDbName, stripJsonc } from '../lib/wrangler.js'

beforeEach(() => {
  vi.clearAllMocks()
  vi.mocked(spawnSync).mockReturnValue({
    pid: 1, output: [], stdout: '[{"success":true,"results":[{"value":1}]}]',
    stderr: '', status: 0, signal: null,
  })
})

describe('Wrangler D1 execution', () => {
  it.each([false, true])('file execution preserves spaced paths without a shell (local=%s)', (local) => {
    const options = { db: 'beech-db', local, configPath: '/Projects/my site/wrangler.jsonc' }

    const result = executeD1File('SELECT 1', options)

    expect(result).toBe(true)
    const [command, args, settings] = vi.mocked(spawnSync).mock.calls[0]
    expect(command).toBe(process.execPath)
    expect(args?.[0]).toMatch(/wrangler[/\\]bin[/\\]wrangler\.js$/)
    expect(args?.slice(1)).toEqual([
      'd1', 'execute', 'beech-db', '--file', expect.stringContaining(join('/tmp/Mario Rossi', 'beech-')),
      '--config', options.configPath, local ? '--local' : '--remote',
    ])
    expect(settings?.shell).toBe(false)
    expect(rmSync).toHaveBeenCalledWith(args?.[5])
  })

  it.each([false, true])('queries preserve spaced paths without a shell (local=%s)', (local) => {
    const options = { db: 'beech-db', local, configPath: '/Projects/my site/wrangler.jsonc' }

    const result = queryD1('SELECT 1 AS value', options)

    expect(result).toEqual([{ value: 1 }])
    const [command, args, settings] = vi.mocked(spawnSync).mock.calls[0]
    expect(command).toBe(process.execPath)
    expect(args?.[0]).toMatch(/wrangler[/\\]bin[/\\]wrangler\.js$/)
    expect(args?.slice(1)).toEqual([
      'd1', 'execute', 'beech-db', '--file', expect.stringContaining(join('/tmp/Mario Rossi', 'beech-')),
      '--json', '--config', options.configPath, local ? '--local' : '--remote',
    ])
    expect(settings?.shell).toBe(false)
    expect(rmSync).toHaveBeenCalledWith(args?.[5])
  })

  it.each([executeD1File, queryD1])('rejects shell syntax before spawning or writing SQL', (execute) => {
    const options = { db: 'x & echo injected', local: false, configPath: null }

    const result = () => execute('SELECT 1', options)

    expect(result).toThrow('Invalid D1 database name')
    expect(spawnSync).not.toHaveBeenCalled()
    expect(writeFileSync).not.toHaveBeenCalled()
  })
})

describe('resolveDbName', () => {
  it.each([
    ['wrangler.jsonc', '{"d1_databases":[{"database_name":"x & echo injected"}]}'],
    ['wrangler.toml', '[[d1_databases]]\ndatabase_name = "x & echo injected"'],
  ])('rejects invalid database names from %s instead of silently defaulting', (path, config) => {
    vi.mocked(readFileSync).mockReturnValue(config)

    const result = () => resolveDbName(path)

    expect(result).toThrow('Invalid D1 database name')
  })

  it('reads the database name from a scaffolded config with comments and URLs in values', () => {
    vi.mocked(readFileSync).mockReturnValue(`{
  // generated by @beechcms/cms
  "vars": { "APP_URL": "http://localhost:5173", "NOTE": "a /* not a comment */ b" },
  /* binding */
  "d1_databases": [
    { "binding": "DB", "database_name": "my-app-db", "database_id": "x", },
  ],
}`)

    const result = resolveDbName('wrangler.jsonc')

    expect(result).toBe('my-app-db')
  })

  it('falls back to the default only when there is no config at all', () => {
    const result = resolveDbName(null)

    expect(result).toBe('beech-db')
  })

  it.each([
    ['wrangler.jsonc', '{ "vars": { "A": '],
    ['wrangler.jsonc', '{ "name": "no-db" }'],
    ['wrangler.toml', 'name = "no-db"'],
  ])('throws instead of defaulting when %s has no readable D1 binding', (path, config) => {
    vi.mocked(readFileSync).mockReturnValue(config)

    const result = () => resolveDbName(path)

    expect(result).toThrow(path)
  })

  it.each(['beech-db', 'site_123', 'DB'])('accepts valid database name %s', (name) => {
    vi.mocked(readFileSync).mockReturnValue(JSON.stringify({ d1_databases: [{ database_name: name }] }))

    const result = resolveDbName('wrangler.jsonc')

    expect(result).toBe(name)
  })
})

describe('findTopLevelObjectSpan', () => {
  const sliceVars = (raw: string): unknown => {
    const span = findTopLevelObjectSpan(raw, 'vars')
    return span ? JSON.parse(stripJsonc(raw.slice(span.open, span.close + 1))) : null
  }

  it('spans exactly the vars object of a 0.10.x-shaped config', () => {
    const raw = `{
  "name": "app-api",
  "compatibility_flags": ["nodejs_compat"],

  "vars": {
    "ENV": "development",
    "APP_URL": "http://localhost:5173"
  },

  "d1_databases": [{ "binding": "DB" }]
}
`

    const result = sliceVars(raw)

    expect(result).toEqual(JSON.parse(stripJsonc(raw)).vars)
  })

  it.each([
    ['a string value', '{ "note": "\\"vars\\": { \\"X\\": 1 }", "vars": { "A": "1" } }', { A: '1' }],
    ['a line comment', '{\n  // "vars": { "X": 1 }\n  "vars": { "A": "1" }\n}', { A: '1' }],
    ['a block comment', '{ /* "vars": { "X": 1 } */ "vars": { "A": "1" } }', { A: '1' }],
    ['env.production', '{ "env": { "production": { "vars": { "X": "1" } } }, "vars": { "A": "1" } }', { A: '1' }],
    ['a string value only', '{ "note": "\\"vars\\": { }" }', null],
    ['a line comment only', '{\n  // "vars": {}\n  "name": "x"\n}', null],
    ['env.production only', '{ "env": { "production": { "vars": { "X": "1" } } } }', null],
  ])('never matches a "vars" inside %s', (_label, raw, expected) => {
    const result = sliceVars(raw)

    expect(result).toEqual(expected)
  })

  it.each([
    ['vars is absent', '{ "name": "app" }'],
    ['vars is an array', '{ "vars": ["A"] }'],
    ['vars is a string', '{ "vars": "A" }'],
    ['the input is unterminated', '{ "vars": { "A": "1" '],
    ['a string is unterminated', '{ "vars": { "A": "1'],
  ])('returns null when %s', (_label, raw) => {
    const result = findTopLevelObjectSpan(raw, 'vars')

    expect(result).toBeNull()
  })
})
